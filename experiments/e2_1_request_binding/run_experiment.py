CSV_FIELDS = [
    "group", "scenario", "trial", "operation_id", "authorized_arguments",
    "executed_arguments", "accepted", "rejection_stage", "rejection_reason",
    "dispatch_count", "unauthorized_effects", "effects", "d10_admission",
    "d11_transition", "authorization_version", "receipt_verified",
]


def write_outputs(result: dict[str, Any], output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    records = result["records"]

    with (output_dir / "trials.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_FIELDS, extrasaction="ignore")
        writer.writeheader()
        for r in records:
            writer.writerow(r)

    with (output_dir / "summary.json").open("w", encoding="utf-8") as f:
        json.dump(result["metrics"], f, indent=2, ensure_ascii=False)
        f.write("\n")

    with (output_dir / "raw.json").open("w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, ensure_ascii=False, default=str)
        f.write("\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--trials", type=int, default=10,
                        help="number of independent samples per condition (default 10)")
    parser.add_argument("--output-dir", type=Path, default=REPO / "experiments" / "e2_1_request_binding" / "results" / "run-001",
                        help="directory for raw CSV/JSON output")
    args = parser.parse_args(argv)

    if args.trials < 1:
        parser.error("--trials must be >= 1")

    print(f"[e2.1] trials={args.trials} output={args.output_dir}", flush=True)
    result = run_experiment(args.trials)
    write_outputs(result, args.output_dir)
    print("[e2.1] done. metrics:", flush=True)
    print(json.dumps(result["metrics"], indent=2, ensure_ascii=False), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
