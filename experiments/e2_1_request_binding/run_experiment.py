# --------------------------------------------------------------------------- #
# Fixed experiment constants (deterministic inputs, no RNG needed)
# --------------------------------------------------------------------------- #
BENIGN_INVOICE = "INV-E16-SYSTEM"
ATTACK_INVOICE = "INV-E16-ATTACK"
BENIGN_ARGUMENTS = {"invoice_id": BENIGN_INVOICE}
ATTACK_ARGUMENTS = {"invoice_id": ATTACK_INVOICE}
TOOL_NAME = "invoice_review"

GROUP_G1 = "G1_STATIC_ACL_SCHEMA"
GROUP_G2 = "G2_SIGNED_TOOL_SCOPE_V1"
GROUP_G3 = "G3_FULL_E1_V2"

SCENARIO_BENIGN = "A_BENIGN"
SCENARIO_SUBSTITUTE = "B_SUBSTITUTE"
SCENARIO_C1 = "C1_BEFORE_ADMISSION"
SCENARIO_C2 = "C2_AFTER_ADMISSION"


# --------------------------------------------------------------------------- #
# Stateful side-effect observer
# --------------------------------------------------------------------------- #
class StatefulEffectRegistry(LocalToolRegistry):
    """Experiment-local tool registry that records every REAL dispatch.

    It inherits the production LocalToolRegistry unchanged (same schema, same
    validate), but appends a durable in-memory effect for each dispatch so the
    experiment observes whether a substituted invoice_id actually reached the
    protected tool.  Each experiment group gets its own instance.
    """

    def __init__(self) -> None:
        super().__init__()
        self.dispatch_count = 0
        self.effects: list[dict[str, Any]] = []

    def dispatch(self, name: str, arguments: Any) -> Any:
        # Record BEFORE delegating, so a real dispatch is always observable.
        self.dispatch_count += 1
        self.effects.append({
            "operation": name,
            "invoice_id": dict(arguments).get("invoice_id"),
        })
        return super().dispatch(name, arguments)

    def unauthorized_effects(self, target: str = ATTACK_INVOICE) -> int:
        return sum(1 for e in self.effects if e["invoice_id"] == target)

    def reset(self) -> None:
        self.dispatch_count = 0
        self.effects = []


# --------------------------------------------------------------------------- #
# Result record
# --------------------------------------------------------------------------- #
def _new_record(group: str, scenario: str, trial: int, operation_id: str) -> dict[str, Any]:
    return {
        "group": group,
        "scenario": scenario,
        "trial": trial,
        "operation_id": operation_id,
        "authorized_arguments": BENIGN_INVOICE,
        "executed_arguments": "",
        "accepted": False,
        "rejection_stage": "",
        "rejection_reason": "",
        "dispatch_count": 0,
        "unauthorized_effects": 0,
        "effects": "",
        "d10_admission": "NOT_APPLICABLE",
        "d11_transition": "NOT_APPLICABLE",
        "authorization_version": "",
        "receipt_verified": "NOT_APPLICABLE",
    }


# --------------------------------------------------------------------------- #
# G1 - Static ACL + Schema (experiment-local reference baseline)
# --------------------------------------------------------------------------- #
def run_g1(h: _SystemHarness, registry: StatefulEffectRegistry, *,
           scenario: str, trial: int, operation_id: str) -> dict[str, Any]:
    """Tool whitelist + schema check only; no argument-value binding.

    This is a minimal reference baseline, not a competing production system.
    """
    rec = _new_record(GROUP_G1, scenario, trial, operation_id)
    args = BENIGN_ARGUMENTS if scenario == SCENARIO_BENIGN else ATTACK_ARGUMENTS
    rec["executed_arguments"] = args["invoice_id"]
    rec["authorization_version"] = "NONE"
    registry.reset()
    try:
        # Static ACL: tool must be in the whitelist.
        if TOOL_NAME not in {"invoice_review"}:
            raise PermissionError("tool not in static whitelist")
        # Schema check: both benign and attack values are schema-valid.
        registry.validate(TOOL_NAME, args)
    except Exception as exc:  # noqa: BLE001 - reference baseline, record any rejection
        rec["rejection_stage"] = "static_acl_or_schema"
        rec["rejection_reason"] = f"{type(exc).__name__}: {exc}"
    else:
        # Gate passed -> real dispatch into the stateful observer.
        registry.dispatch(TOOL_NAME, args)
        rec["accepted"] = True
    rec["dispatch_count"] = registry.dispatch_count
    rec["unauthorized_effects"] = registry.unauthorized_effects()
    rec["effects"] = json.dumps(registry.effects, sort_keys=True)
    # No D10/D11 in this baseline.
    return rec


# --------------------------------------------------------------------------- #
# G2 - Signed Tool-Scope Authorization v1 (experiment-local reference baseline)
# --------------------------------------------------------------------------- #
def run_g2(h: _SystemHarness, registry: StatefulEffectRegistry,
           issuer_private_key: Ed25519PrivateKey, *,
           scenario: str, trial: int, operation_id: str) -> dict[str, Any]:
    """Sign a real v1 Executor Authorization (no arguments) and verify it with
    require_argument_binding=False, then dispatch the substituted arguments.

    v1 binds executor + tool + schema + grant scope but carries NO arguments
    digest, so a value substitution is invisible to authorization verification.
    This is a controlled ablation reference baseline, not a deployable E1 mode.
    """
    rec = _new_record(GROUP_G2, scenario, trial, operation_id)
    args = BENIGN_ARGUMENTS if scenario == SCENARIO_BENIGN else ATTACK_ARGUMENTS
    rec["executed_arguments"] = args["invoice_id"]
    registry.reset()

    ctx = h.new_context(operation_id, BUDGET_ID_N, PERIOD_ID_N, register=False)
    try:
        # Issue a REAL v1 authorization by omitting `arguments`.
        auth_v1 = issue_executor_authorization(
            issuer_private_key,
            issuer_id=h.issuer_id,
            authorization_id=f"auth-g2-{operation_id}",
            online_lease_grant=h.lease,
            execution_grant=ctx.execution,
            gateway_id=h.gateway_id,
            coordinator_id=h.coordinator_id,
            executor_id=h.executor_id,
            executor_public_key=h.executor_key.public_key(),
            tool_name=TOOL_NAME,
            tool_schema_hash=h.schema_hash,
            issued_at=h.now - 20,
            expires_at=h.now + 1800,
            # arguments intentionally omitted -> version 1, no arguments_digest
        )
        rec["authorization_version"] = str(auth_v1.payload["version"])
        # Verify signature + tool scope, WITHOUT argument-value binding.
        verify_executor_authorization(
            auth_v1, h.issuer.public_key(),
            online_lease_grant=h.lease,
            execution_grant=ctx.execution,
            gateway_id=h.gateway_id,
            coordinator_id=h.coordinator_id,
            executor_id=h.executor_id,
            tool_name=TOOL_NAME,
            tool_schema_hash=h.schema_hash,
            now=h.now,
            # expected_arguments_digest / require_argument_binding omitted (False)
        )
        registry.validate(TOOL_NAME, args)
    except Exception as exc:  # noqa: BLE001 - reference baseline
        rec["rejection_stage"] = "v1_authorization_or_schema"
        rec["rejection_reason"] = f"{type(exc).__name__}: {exc}"
    else:
        registry.dispatch(TOOL_NAME, args)
        rec["accepted"] = True
    rec["dispatch_count"] = registry.dispatch_count
    rec["unauthorized_effects"] = registry.unauthorized_effects()
    rec["effects"] = json.dumps(registry.effects, sort_keys=True)
    return rec


# --------------------------------------------------------------------------- #
# G3 - Full E1 strict v2 four-gate chain (real production code)
# --------------------------------------------------------------------------- #
def run_g3_benign(h: _SystemHarness, ex, registry: StatefulEffectRegistry, *,
                  trial: int, operation_id: str) -> dict[str, Any]:
    """Scenario A: normal request through the real four-gate E1 chain."""
    rec = _new_record(GROUP_G3, SCENARIO_BENIGN, trial, operation_id)
    rec["executed_arguments"] = BENIGN_INVOICE
    rec["authorization_version"] = "2"
    registry.reset()
    ctx = h.new_context(operation_id, BUDGET_ID_N, PERIOD_ID_N, register=False)
    try:
        pending = h.run(ctx)
        receipt = h.execute(ex, h, pending, ctx)
        tcb = _binding_from_pending(pending)
        rec["receipt_verified"] = str(bool(ex.verify_receipt(receipt, binding=tcb)))
        rec["accepted"] = receipt["payload"]["status"] == "SUCCEEDED"
    except Exception as exc:  # noqa: BLE001 - record real rejection
        rec["rejection_stage"] = "e1_four_gate"
        rec["rejection_reason"] = f"{type(exc).__name__}: {exc}"
    rec["dispatch_count"] = registry.dispatch_count
    rec["unauthorized_effects"] = registry.unauthorized_effects()
    rec["effects"] = json.dumps(registry.effects, sort_keys=True)
    rec["d10_admission"] = "COMMITTED" if h.d10_state()["operations"] > 0 else "NONE"
    d11 = h.d11_state(ctx)
    rec["d11_transition"] = "COMMITTED" if d11["version"] else "NONE"
    return rec


def run_g3_c1(h: _SystemHarness, ex, registry: StatefulEffectRegistry, *,
              trial: int, operation_id: str) -> dict[str, Any]:
    """Scenario C1: substitute ctx.arguments BEFORE Admission, then h.run()."""
    rec = _new_record(GROUP_G3, SCENARIO_C1, trial, operation_id)
    rec["executed_arguments"] = ATTACK_INVOICE  # attempted value
    rec["authorization_version"] = "2"
    registry.reset()
    # Authorization is issued for BENIGN via new_context(); tamper the context.
    ctx = h.new_context(operation_id, BUDGET_ID_N, PERIOD_ID_N, register=False)
    ctx.arguments = dict(ATTACK_ARGUMENTS)
    d10_before = h.d10_state()
    try:
        h.run(ctx)  # expected to fail closed in precheck (arguments digest)
        rec["accepted"] = True  # would only be true if the attack slipped through
        rec["rejection_stage"] = "NONE"
    except (E1FailClosed, ExecutorAuthorizationError, ToolExecutionDenied, ValueError) as exc:
        rec["rejection_stage"] = "runtime_precheck_before_d10"
        rec["rejection_reason"] = f"{type(exc).__name__}: {exc}"
    rec["dispatch_count"] = registry.dispatch_count
    rec["unauthorized_effects"] = registry.unauthorized_effects()
    rec["effects"] = json.dumps(registry.effects, sort_keys=True)
    d10_after = h.d10_state()
    rec["d10_admission"] = "NONE" if d10_after == d10_before else "CHANGED"
    rec["d11_transition"] = "NONE"  # no run() -> no submit_transition
    rec["receipt_verified"] = "NO_RECEIPT"
    # Attach evidence for the report.
    rec["d10_state"] = d10_after
    return rec


def run_g3_c2(h: _SystemHarness, ex, registry: StatefulEffectRegistry, *,
              trial: int, operation_id: str) -> dict[str, Any]:
    """Scenario C2: normal run(), then replace PendingExecution.arguments before
    the final Executor gate, then call execute_e1()."""
    rec = _new_record(GROUP_G3, SCENARIO_C2, trial, operation_id)
    rec["executed_arguments"] = ATTACK_INVOICE  # attempted value
    rec["authorization_version"] = "2"
    registry.reset()
    ctx = h.new_context(operation_id, BUDGET_ID_N, PERIOD_ID_N, register=False)
    pending = h.run(ctx)  # D10 + D11 admission already committed here
    d11_after_run = h.d11_state(ctx)
    rec["d10_admission"] = "COMMITTED"
    rec["d11_transition"] = "COMMITTED" if d11_after_run["version"] else "NONE"

    forged = dataclasses.replace(pending, arguments=dict(ATTACK_ARGUMENTS))
    try:
        h.execute(ex, h, forged, ctx)
        rec["accepted"] = True
        rec["rejection_stage"] = "NONE"
    except ToolExecutionDenied as exc:
        rec["rejection_stage"] = "executor_final_gate"
        rec["rejection_reason"] = f"{type(exc).__name__}: {exc}"
    rec["dispatch_count"] = registry.dispatch_count
    rec["unauthorized_effects"] = registry.unauthorized_effects()
    rec["effects"] = json.dumps(registry.effects, sort_keys=True)
    # Honest Saga evidence: admission stays committed even though exec was denied.
    rec["d11_state_after_denial"] = h.d11_state(ctx)
    rec["receipt_verified"] = "NO_RECEIPT" if ex.store.get_receipt(operation_id) is None else "RECEIPT_PRESENT"
    return rec


def run_g3_replay(h: _SystemHarness, ex, registry: StatefulEffectRegistry, *,
                  trial: int, operation_id: str) -> dict[str, Any]:
    """Exact replay of a benign operation returns the original receipt and does
    not dispatch a second time."""
    rec = _new_record(GROUP_G3, "D_EXACT_REPLAY", trial, operation_id)
    rec["executed_arguments"] = BENIGN_INVOICE
    rec["authorization_version"] = "2"
    registry.reset()
    ctx = h.new_context(operation_id, BUDGET_ID_N, PERIOD_ID_N, register=False)
    pending = h.run(ctx)
    receipt1 = h.execute(ex, h, pending, ctx)
    dispatch_after_first = registry.dispatch_count
    receipt2 = h.execute(ex, h, pending, ctx)
    rec["accepted"] = receipt1 == receipt2
    rec["dispatch_count"] = registry.dispatch_count
    rec["effects"] = json.dumps(registry.effects, sort_keys=True)
    rec["receipt_verified"] = f"IDENTICAL={receipt1 == receipt2}"
    rec["replay_dispatch_before"] = dispatch_after_first
    rec["d10_admission"] = "COMMITTED"
    d11 = h.d11_state(ctx)
    rec["d11_transition"] = "COMMITTED" if d11["version"] else "NONE"
    return rec


# --------------------------------------------------------------------------- #
# Experiment orchestration
# --------------------------------------------------------------------------- #
def run_experiment(trials: int) -> dict[str, Any]:
    """Run all groups/scenarios and return raw records + computed metrics."""
    records: list[dict[str, Any]] = []

    # A dummy TestCase-like object for harness cleanup (harness calls addCleanup
    # and stores state on `case`; a tiny shim keeps this script standalone).
    class _Case:
        def __init__(self) -> None:
            self._cleanups: list[Any] = []

        def addCleanup(self, fn: Any, *a: Any, **kw: Any) -> None:
            self._cleanups.append((fn, a, kw))

        def cleanup(self) -> None:
            for fn, a, kw in reversed(self._cleanups):
                try:
                    fn(*a, **kw)
                except Exception:  # noqa: BLE001
                    pass

    serial = 0

    def oid(tag: str, i: int) -> str:
        nonlocal serial
        serial += 1
        return f"op-e21-{tag}-{i}-{serial}"

    # ---- G1 / G2: no D10/D11 needed; share one harness, no admission usage --
    case = _Case()
    h = _SystemHarness(case)  # noqa: SLF001 - experiment uses the real harness
    try:
        reg_g1 = StatefulEffectRegistry()
        reg_g2 = StatefulEffectRegistry()
        for i in range(trials):
            records.append(run_g1(
                h, reg_g1, scenario=SCENARIO_BENIGN, trial=i,
                operation_id=oid("g1-benign", i),
            ))
            records.append(run_g1(
                h, reg_g1, scenario=SCENARIO_SUBSTITUTE, trial=i,
                operation_id=oid("g1-attack", i),
            ))
            records.append(run_g2(
                h, reg_g2, h.issuer,
                scenario=SCENARIO_BENIGN, trial=i,
                operation_id=oid("g2-benign", i),
            ))
            records.append(run_g2(
                h, reg_g2, h.issuer,
                scenario=SCENARIO_SUBSTITUTE, trial=i,
                operation_id=oid("g2-attack", i),
            ))
    finally:
        case.cleanup()

    # ---- G3 benign + C2/C1/replay: fresh harness per sample ---------------
    # Each harness owns an independent D10 lease, D11 DB and Rust service, so
    # independent samples never share quota or state. All contexts reuse the
    # scope that harness registered at init via (BUDGET_ID_N, PERIOD_ID_N);
    # only operation_id is unique per sample (no D11 SCOPE_CONFLICT).
    for i in range(trials):
        # Benign G3
        case = _Case()
        h = _SystemHarness(case)  # noqa: SLF001
        reg = StatefulEffectRegistry()
        ex = h.executor(registry=reg)
        try:
            records.append(run_g3_benign(
                h, ex, reg, trial=i, operation_id=oid("g3-benign", i),
            ))
        finally:
            case.cleanup()

        # C2 after-admission substitution
        case = _Case()
        h = _SystemHarness(case)  # noqa: SLF001
        reg = StatefulEffectRegistry()
        ex = h.executor(registry=reg)
        try:
            records.append(run_g3_c2(
                h, ex, reg, trial=i, operation_id=oid("g3-c2", i),
            ))
        finally:
            case.cleanup()

    # ---- C1 before-admission substitution (no admission at all) -----------
    for i in range(trials):
        case = _Case()
        h = _SystemHarness(case)  # noqa: SLF001
        reg = StatefulEffectRegistry()
        ex = h.executor(registry=reg)
        try:
            records.append(run_g3_c1(
                h, ex, reg, trial=i, operation_id=oid("g3-c1", i),
            ))
        finally:
            case.cleanup()

    # ---- exact replay (1 sample per trial count) --------------------------
    for i in range(trials):
        case = _Case()
        h = _SystemHarness(case)  # noqa: SLF001
        reg = StatefulEffectRegistry()
        ex = h.executor(registry=reg)
        try:
            records.append(run_g3_replay(
                h, ex, reg, trial=i, operation_id=oid("g3-replay", i),
            ))
        finally:
            case.cleanup()

    metrics = compute_metrics(records, trials)
    return {
        "meta": {
            "experiment": "E2.1-request-binding",
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "trials": trials,
            "baseline_commit": "467fa249c2c7f6971dd9f217ce0827e6f7bfc995",
            "branch": "exp/e2.1-request-binding",
            "python": sys.version.split()[0],
            "benign_invoice": BENIGN_INVOICE,
            "attack_invoice": ATTACK_INVOICE,
            "tool": TOOL_NAME,
        },
        "records": records,
        "metrics": metrics,
    }


def compute_metrics(records: list[dict[str, Any]], trials: int) -> dict[str, Any]:
    def subset(group: str, scenario: str) -> list[dict[str, Any]]:
        return [r for r in records if r["group"] == group and r["scenario"] == scenario]

    def rate(num: int, den: int) -> float:
        return round(num / den, 4) if den else 0.0

    out: dict[str, Any] = {}
    for group in (GROUP_G1, GROUP_G2):
        benign = subset(group, SCENARIO_BENIGN)
        attack = subset(group, SCENARIO_SUBSTITUTE)
        out[group] = {
            "benign_requests": len(benign),
            "benign_accepted": sum(1 for r in benign if r["accepted"]),
            "benign_acceptance_rate": rate(
                sum(1 for r in benign if r["accepted"]), len(benign)),
            "attack_attempts": len(attack),
            "attack_accepted": sum(1 for r in attack if r["accepted"]),
            "attack_rejection_rate": rate(
                sum(1 for r in attack if not r["accepted"]), len(attack)),
            "dispatch_count": sum(r["dispatch_count"] for r in benign + attack),
            "unauthorized_effects": sum(r["unauthorized_effects"] for r in attack),
            "unauthorized_effect_rate": rate(
                sum(r["unauthorized_effects"] for r in attack), len(attack)),
        }

    g3_benign = subset(GROUP_G3, SCENARIO_BENIGN)
    g3_c1 = subset(GROUP_G3, SCENARIO_C1)
    g3_c2 = subset(GROUP_G3, SCENARIO_C2)
    g3_replay = subset(GROUP_G3, "D_EXACT_REPLAY")
    g3_attacks = g3_c1 + g3_c2
    out[GROUP_G3] = {
        "benign_requests": len(g3_benign),
        "benign_accepted": sum(1 for r in g3_benign if r["accepted"]),
        "benign_acceptance_rate": rate(
            sum(1 for r in g3_benign if r["accepted"]), len(g3_benign)),
        "attack_attempts": len(g3_attacks),
        "attack_accepted": sum(1 for r in g3_attacks if r["accepted"]),
        "attack_rejection_rate": rate(
            sum(1 for r in g3_attacks if not r["accepted"]), len(g3_attacks)),
        "dispatch_count_attack": sum(r["dispatch_count"] for r in g3_attacks),
        "unauthorized_effects": sum(r["unauthorized_effects"] for r in g3_attacks),
        "unauthorized_effect_rate": rate(
            sum(r["unauthorized_effects"] for r in g3_attacks), len(g3_attacks)),
        "c1": {
            "attempts": len(g3_c1),
            "rejected": sum(1 for r in g3_c1 if not r["accepted"]),
            "d10_none": sum(1 for r in g3_c1 if r["d10_admission"] == "NONE"),
            "d11_none": sum(1 for r in g3_c1 if r["d11_transition"] == "NONE"),
            "dispatch_count": sum(r["dispatch_count"] for r in g3_c1),
        },
        "c2": {
            "attempts": len(g3_c2),
            "rejected": sum(1 for r in g3_c2 if not r["accepted"]),
            "d10_committed": sum(1 for r in g3_c2 if r["d10_admission"] == "COMMITTED"),
            "d11_committed": sum(1 for r in g3_c2 if r["d11_transition"] == "COMMITTED"),
            "dispatch_count": sum(r["dispatch_count"] for r in g3_c2),
            "no_receipt": sum(1 for r in g3_c2 if r["receipt_verified"] == "NO_RECEIPT"),
        },
        "exact_replay": {
            "samples": len(g3_replay),
            "identical_receipt": sum(
                1 for r in g3_replay if r["receipt_verified"].startswith("IDENTICAL=True")),
            "dispatch_after_replay": sum(r["dispatch_count"] for r in g3_replay),
        },
    }
    return out


# --------------------------------------------------------------------------- #
