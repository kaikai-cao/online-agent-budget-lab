#!/usr/bin/env python3
"""E2.1 - Agent Exec Binding security-effectiveness experiment.

Research question
-----------------
Can a signed tool authorization stop an attacker who keeps the tool name and
argument *structure* valid but replaces an argument VALUE after authorization,
so the tool executes an operation the grant did not precisely bind?

This script records what actually reached the tool (side effects on a stateful
registry), not merely exception types.  It never modifies production code: the
comparison baselines (G1/G2) are experiment-local reference implementations and
G3 reuses the repository's real four-gate E1 execution chain verbatim.

Groups
------
G1 Static ACL + Schema      : tool whitelist + schema, no argument-value binding.
G2 Signed Tool-Scope (v1)   : real Ed25519 Executor Authorization v1 (binds
                              executor/tool/schema/scope but NOT argument digest),
                              verified with require_argument_binding=False.
G3 Full E1 (strict v2)      : real TrustedToolExecutor(e1_required=True) +
                              execute_e1() four gates + real Rust e1_service.

All data is generated by actually running the code; expected results are never
hard-coded into the output.
"""

